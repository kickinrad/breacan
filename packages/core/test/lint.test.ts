// `breacan lint` fails a hand-typed colour, motion, type size, radius, spacing or z-index in any source file, and an
// addon adds rules through a part's `rules`. Ported from tests/lint.test.ts, less its Beer check.
import { afterAll, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";

const core = join(import.meta.dir, "..");
const dirs: string[] = [];
afterAll(() => { for (const dir of dirs) rmSync(dir, { recursive: true, force: true }); });

const project = (files: Record<string, string>) => {
  const dir = mkdtempSync(join(tmpdir(), "breacan-lint-"));
  dirs.push(dir);
  mkdirSync(join(dir, "node_modules"));
  symlinkSync(core, join(dir, "node_modules/breacan"));
  writeFileSync(join(dir, "theme.toml"), "");
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, path)), { recursive: true });
    writeFileSync(join(dir, path), content);
  }
  return dir;
};
const lint = (dir: string, ...paths: string[]) => {
  const { exitCode, stdout, stderr } = Bun.spawnSync(["bun", join(core, "bin/breacan.mjs"), "lint", ...paths], { cwd: dir });
  return { code: exitCode, out: stdout.toString(), err: stderr.toString() };
};
const flagged = (name: string, content: string, finding: string) => {
  const result = lint(project({ [name]: content }), name);
  expect(result.code).toBe(1);
  expect(result.out.trim()).toBe(`${name}:${finding}`);
};
const clean = (name: string, content: string) => expect(lint(project({ [name]: content }), name).code).toBe(0);

test("colour: 3, 4, 6 and 8-digit hex, rgb() and Kotlin Color(0x) fail; var() and repo#123 refs pass", () => {
  flagged("a.css", "a { color: #fff; }\n", "1: colour: #fff");
  flagged("a.css", "a { color: #000a; }\n", "1: colour: #000a");
  flagged("a.css", "a { color: #1a2b3c; }\n", "1: colour: #1a2b3c");
  flagged("a.css", "a { color: #1a2b3cff; }\n", "1: colour: #1a2b3cff");
  flagged("a.css", "a { color: rgba(0, 0, 0, .5); }\n", "1: colour: rgba(0");
  flagged("A.kt", "val c = Color(0xFF112233)\n", "1: colour: Color(0xFF112233");
  clean("a.css", "a { color: var(--color-accent-default); } /* see otto#107 */\n");
});

test("motion, type size, radius, spacing and z-index fail, in CSS and Compose", () => {
  flagged("a.css", "a { transition: opacity 120ms ease; }\n", "1: motion: 120ms");
  flagged("a.css", "a { transition: opacity var(--d) cubic-bezier(.2, 0, 0, 1); }\n", "1: motion: cubic-bezier(");
  flagged("Home.kt", "val s = tween(160)\n", "1: motion: 160");
  flagged("a.css", "a { font-size: 14px; }\n", "1: type size: 14px");
  flagged("T.kt", "val t = TextStyle(fontSize = 24.sp)\n", "1: type size: 24.sp");
  flagged("a.css", "a { border-radius: 12px; }\n", "1: radius: 12px");
  flagged("S.kt", "val s = RoundedCornerShape(8.dp)\n", "1: radius: 8.dp");
  flagged("a.css", "a { padding: 0 16px; }\n", "1: spacing: 16px");
  flagged("S.kt", "val s = Modifier.padding(16.dp)\n", "1: spacing: 16.dp");
  flagged("a.css", "a { z-index: 20; }\n", "1: z-index: 20");
  flagged("S.kt", "val s = Modifier.zIndex(3)\n", "1: z-index: 3");
  clean("a.css", "a { margin: 0; z-index: 0; font-size: var(--t); transition: opacity var(--d); }\n.slow { width: 10s; }\n");
});

test("a value in .astro, .tsx, .jsx, .vue and .svelte is flagged", () => {
  const markup = "<style>\n  a { color: #112233; }\n</style>\n";
  for (const name of ["a.astro", "a.tsx", "a.jsx", "a.vue", "a.svelte"]) flagged(name, markup, "2: colour: #112233");
});

test("a generated file is skipped, and `lint: own <why>` skips its line; an empty reason does not", () => {
  clean("a.css", "/* Generated by Breacán from theme: do not edit; rebuild. */\na { color: #112233; }\n");
  const dir = project({ "a.css": "a { color: #112233; } /* lint: own brand mark */\n", "b.css": "a { color: #112233; } /* lint: own */\n" });
  expect(lint(dir, "a.css").code).toBe(0);
  expect(lint(dir, "b.css").out.trim()).toBe("b.css:1: colour: #112233");
});

test("a directory is walked; node_modules, dot-directories and other extensions are skipped", () => {
  const bad = "a { color: #112233; }\n";
  const dir = project({ "src/deep/a.css": bad, "src/node_modules/x.css": bad, "src/.cache/y.css": bad, "src/notes.txt": bad });
  expect(lint(dir, "src").out.trim()).toBe(`${join("src", "deep", "a.css")}:1: colour: #112233`);
});

test("a clean project exits 0 with no output; a missing path fails naming it", () => {
  const dir = project({ "a.css": "a { color: var(--c); }\n" });
  expect(lint(dir, "a.css")).toEqual({ code: 0, out: "", err: "" });
  const missing = lint(dir, "nope");
  expect(missing.code).toBe(1);
  expect(missing.err).toContain("nope");
});

test("an addon's rules join the built-ins, and an `extensions` list limits where one runs", () => {
  const config = `import { defineConfig, defineOutput } from "breacan";
const ban = defineOutput({ name: "ban", write: () => [], rules: [
  { name: "emoji", extensions: [".astro"], check: (line) => line.match(/🔥/g) ?? [] },
] });
export default defineConfig({ addons: [{ name: "ban-addon", parts: [ban] }] });\n`;
  const dir = project({ "breacan.config.ts": config, "a.astro": "<p>🔥</p>\n", "a.vue": "<p>🔥</p>\n", "b.css": "a { color: #fff; }\n" });
  const result = lint(dir, ".");
  expect(result.code).toBe(1);
  expect(result.out.trim().split("\n")).toEqual(["a.astro:1: emoji: 🔥", "b.css:1: colour: #fff"]);
});
